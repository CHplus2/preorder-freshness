import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createServer} from 'vite';
import {MemoryRouter} from 'react-router-dom';

const server = await createServer({server:{middlewareMode:true,hmr:false}, appType:'custom'});
try {
 const {StoreContext}=await server.ssrLoadModule('/src/contexts/StorefrontContext.js');
 const renderScheduled=node=>renderToStaticMarkup(createElement(StoreContext.Provider,{value:{store:{ordering_mode:'scheduled'}}},node));
  const {default: AvailabilityResult} = await server.ssrLoadModule('/src/components/AvailabilityResult.jsx');
  const quote = {selectionKey:'basket-and-date', plan:{preparation_at:'2026-10-01T03:00:00Z', hands_on_minutes:30, procurement_required:false}};
  const render = props => renderToStaticMarkup(createElement(AvailabilityResult, {selectionKey:'basket-and-date', quote, ...props}));
  assert.match(render({}), /Your requested time is available/);
  assert.match(render({}), /continue to place your preorder/);
  assert.match(render({}), /stock is not reserved/);
  const multi=render({quote:{...quote,plan:{...quote.plan,daily_work:[
    {date:'2026-10-19',hands_on_minutes:490,pause_minutes:240,task_count:2},
    {date:'2026-10-20',hands_on_minutes:510,pause_minutes:480,task_count:2}]}}});
  assert.match(multi,/Preparation across 2 days/);assert.match(multi,/8h 10m hands-on/);
  assert.match(multi,/planned pause/);assert.match(multi,/Your requested time is available/);
  assert.match(render({quote:{...quote, plan:{...quote.plan, procurement_required:true}}}), /needs to purchase ingredients/);
  const manual=render({quote:{...quote,plan:{needs_review:true,preparation_at:null}}});
  assert.match(manual,/Kitchen confirmation needed/);
  assert.match(manual,/No payment will be taken/);
  assert.doesNotMatch(manual,/Your requested time is available|Preparation starts/);
  const changed=render({requestMode:false,quote:{...quote,plan:{needs_review:true,review_reason:'Private recipe timing explanation'}}});
  assert.match(changed,/Choose another available time/);
  assert.doesNotMatch(changed,/Private recipe timing explanation|You can send this time/);
  const stale = render({selectionKey:'changed-basket'});
  assert.match(stale, /Please check availability again/);
  assert.doesNotMatch(stale, /Your requested time is available/);
  assert.match(render({checking:true}), /Checking kitchen availability/);
  const failed = render({error:'No available slot for Granola Bar'});
  assert.match(failed, /No available slot for Granola Bar/);
  assert.doesNotMatch(failed, /Your requested time is available/);
  const retry=render({error:'Temporarily unavailable',retryable:true,onRetry:()=>{}});
  assert.match(retry, /<div class="availability-result-actions"><button type="button">Retry availability check<\/button><\/div><\/div>/);
  assert.doesNotMatch(render({checking:true,retryable:true,onRetry:()=>{}}), /Retry availability check/);
  assert.doesNotMatch(render({error:'Choose another date',retryable:false,onRetry:()=>{}}), /Retry availability check/);

  assert.doesNotMatch(render({quote:null}), /Your requested time is available/);
  const shortages={rows:[{raw_material_id:'7',name:'Chicken boneless trimmed',unit:'g',required:'180',available:'0',shortfall:'180'},{raw_material_id:'8',name:'Salt',unit:'g',required:'15',available:'0',shortfall:'15'}],count:2};
  const stock=renderToStaticMarkup(createElement(MemoryRouter,null,createElement(AvailabilityResult,{error:'Long technical stock message',shortage:shortages,retryable:true,onRetry:()=>{}})));
  assert.match(stock,/This basket isn’t available for the selected date/);
  assert.doesNotMatch(stock,/Chicken|Salt|180|Needed|Available 0|Which stock counts|recorded deadline/);
  assert.match(stock,/Edit basket/);assert.match(stock,/Ask the kitchen/);assert.match(stock,/Check availability again/);assert.match(stock,/href="#checkout-time"/);
  assert.doesNotMatch(stock,/Long technical stock message|Availability could not be confirmed/);
  const {stockShortage}=await server.ssrLoadModule('/src/utils/stockShortage.js');
  const payload={code:'ingredient_stock_shortage',shortages:shortages.rows,shortage_count:'2'};
  assert.equal(stockShortage(payload).rows.length,2);
  for(const field of ['required','available','shortfall'])assert.equal(stockShortage({...payload,shortages:[{...shortages.rows[0],[field]:'NaN'}]}),null);
  assert.equal(stockShortage({...payload,shortages:[shortages.rows[0],shortages.rows[0]]}),null);
  assert.equal(stockShortage({...payload,shortages:[{...shortages.rows[0],shortfall:'12'}]}),null);
  const packagingPayload={code:'packaging_stock_shortage',shortages:[{packaging_item_id:'9',name:'Meal container',unit:'pieces',required:'3',available:'1',shortfall:'2'}],shortage_count:'1'};
  const packagingShortage=stockShortage(packagingPayload);assert.equal(packagingShortage.kind,'packaging');
  const packaging=renderToStaticMarkup(createElement(MemoryRouter,null,createElement(AvailabilityResult,{error:'Packaging shortage',shortage:packagingShortage,retryable:true,onRetry:()=>{}})));
  assert.match(packaging,/This basket isn’t available for the selected date/);assert.match(packaging,/Check availability again/);assert.doesNotMatch(packaging,/Meal container|pieces|recorded packaging|recorded deadline/);
  const redacted=renderToStaticMarkup(createElement(MemoryRouter,null,createElement(AvailabilityResult,{error:'Unavailable',shortage:{kind:'ingredient'},retryable:true,onRetry:()=>{}})));
  assert.match(redacted,/Change date or time/);assert.doesNotMatch(redacted,/Unavailable|ingredients/);
  const simple=render({quote:{...quote,plan:{ordering_mode:'simple'}}});
  assert.match(simple,/Your selected date and time are available/);assert.doesNotMatch(simple,/ingredient|packaging|deducted/);
  assert.equal(stockShortage({...packagingPayload,shortages:[{...packagingPayload.shortages[0],required:'3.5',shortfall:'2.5'}]}),null);
  const {default: BasketSlots} = await server.ssrLoadModule('/src/components/BasketSlots.jsx');
  const initialSlots=renderToStaticMarkup(createElement(BasketSlots,{value:'',onSelect:()=>{}}));
  assert.doesNotMatch(initialSlots,/No hourly slots found|Suggest times for this basket|Find the next available day|Search later dates/);
  assert.equal((initialSlots.match(/Find delivery times/g) || []).length,1);
  const {default:DeliveryTimePicker}=await server.ssrLoadModule('/src/components/DeliveryTimePicker.jsx');
  const picker=props=>renderScheduled(createElement(MemoryRouter,null,createElement(DeliveryTimePicker,{cart:[{id:1,quantity:1,product:{id:1,lead_hours:24}}],onSelect:()=>{},allowRequest:true,onRequestMode:()=>{},...props})));
  const automatic=picker({});assert.match(automatic,/Finding available times for your whole basket/);
  assert.match(automatic,/Need a different time\? Ask the kitchen/);
  assert.doesNotMatch(automatic,/type="datetime-local"|No hourly suggestions|Check availability/);
  const requested=picker({requestMode:true});assert.match(requested,/type="datetime-local"/);
  assert.match(requested,/This is a custom request/);
  assert.match(requested,/Choose an available time instead/);
  const {default: RecipeEditor} = await server.ssrLoadModule('/src/components/RecipeEditor.jsx');
  const flexible=renderScheduled(createElement(RecipeEditor,{value:{max_early_minutes:0,max_preparation_days:2},onChange:()=>{}}));
  assert.match(flexible,/Flexible on the dispatch day/);assert.match(flexible,/Completed food does not occupy the worker/);
  assert.doesNotMatch(flexible,/finish exactly|Zero early finish|May finish up to/);
  const limited=renderScheduled(createElement(RecipeEditor,{value:{max_early_minutes:120,max_preparation_days:2},onChange:()=>{}}));
  assert.match(limited,/May finish up to/);
  console.log('Availability result: success, procurement, stale selection, pending, failure and initial state passed.');
} finally {
  await server.close();
}
