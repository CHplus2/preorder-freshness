import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {MemoryRouter} from 'react-router-dom';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true,hmr:false},appType:'custom'});
try{
 const {default:MenuListingStatus}=await server.ssrLoadModule('/src/components/MenuListingStatus.jsx');
 const status=p=>renderToStaticMarkup(createElement(MenuListingStatus,p));
 assert.match(status({error:true,count:0,shown:0}),/temporarily unavailable/);
 assert.doesNotMatch(status({error:true,count:0,shown:0}),/0 items found/);
 assert.match(status({loading:true,count:0,shown:0}),/Loading menu/);
 assert.match(status({count:1,shown:1}),/1 item found/);
 const {DeliveryChangePreview}=await server.ssrLoadModule('/src/components/RescheduleOrder.jsx');
 const deliveryPreview=needs_review=>renderToStaticMarkup(createElement(DeliveryChangePreview,{preview:{needs_review,previous_delivery:'2026-10-20T16:00:00+08:00',delivery_at:'2026-10-21T15:22:00+08:00',reason:'Later request',change_closes_at:needs_review?null:'2026-10-20T12:00:00+08:00'}}));
 const requested=deliveryPreview(true);assert.match(requested,/Save requested time/);assert.match(requested,/no preparation slots are reserved/);assert.doesNotMatch(requested,/Confirm new time|Deadline for any further changes/);
 const reserved=deliveryPreview(false);assert.match(reserved,/Confirm new time/);assert.match(reserved,/Deadline for any further changes/);assert.doesNotMatch(reserved,/Save requested time/);
 const {default:PaymentOptions}=await server.ssrLoadModule('/src/components/PaymentOptions.jsx');
 const payment=p=>renderToStaticMarkup(createElement(MemoryRouter,null,createElement(PaymentOptions,{value:'cod',onChange:()=>{},...p})));
 const html=payment({manualEnabled:true});
 assert.match(html,/Cash on delivery/);assert.match(html,/DuitNow QR/);
 const demo=html.slice(html.indexOf('<details'));
 assert.match(demo,/Demo credit wallet/);assert.doesNotMatch(demo,/<details[^>]*\sopen/);
 assert.doesNotMatch(payment({manualEnabled:false}),/DuitNow QR/);
 assert.match(payment({value:'wallet'}),/demo wallet selected/);
 const {default:BasketDeliveryDays}=await server.ssrLoadModule('/src/components/BasketDeliveryDays.jsx');
 const basket=(cart,value='')=>renderToStaticMarkup(createElement(MemoryRouter,null,createElement(BasketDeliveryDays,{cart,value})));
 const meal=(name,delivery_weekdays)=>({product:{name,delivery_weekdays}});
 assert.equal(basket([meal('Everyday',[])]),'');
 assert.match(basket([meal('Weekend',[5,6])]),/Saturday, Sunday/);
 const conflict=basket([meal('Monday',[0]),meal('Saturday',[5])]);
 assert.match(conflict,/no delivery weekday in common/);
 assert.match(conflict,/href="\/cart"/);
 const inBasket=renderToStaticMarkup(createElement(MemoryRouter,null,createElement(BasketDeliveryDays,{cart:[meal('Monday',[0]),meal('Saturday',[5])],value:'',showBasketLink:false})));
 assert.match(inBasket,/no delivery weekday in common/);
 assert.doesNotMatch(inBasket,/href="\/cart"/);
 assert.match(basket([meal('Saturday',[5])],'2026-10-11T16:00'),/cannot be delivered/);
 const {ContributionSummary,OrderContribution}=await server.ssrLoadModule('/src/components/ContributionEvidence.jsx');
 const contributionSummary=report=>renderToStaticMarkup(createElement(ContributionSummary,{report}));
 const contributionBase={known_contribution:'0.00',complete_orders:0,shown:2,order_count:2};
 assert.match(contributionSummary(contributionBase),/Contribution total unavailable/);
 assert.doesNotMatch(contributionSummary(contributionBase),/<strong>RM 0.00<\/strong>/);
 assert.match(contributionSummary({...contributionBase,complete_orders:1}),/<strong>RM 0.00<\/strong>/);
 assert.match(contributionSummary({...contributionBase,known_contribution:'-2.00',complete_orders:1}),/RM -2.00/);
 assert.match(contributionSummary({...contributionBase,shown:0,order_count:0}),/No orders were placed/);
 assert.match(contributionSummary(contributionBase),/date placed/);
 const contributionRow={order:1,status:'pending',realised:false,food_contribution:null,net_food_revenue:'0',known_ingredient_cost:'0',accepted_packaging_cost:'0',missing:['Missing cooking evidence'],trace:[]};
 const orderEvidence=changes=>renderToStaticMarkup(createElement(OrderContribution,{row:{...contributionRow,...changes}}));
 assert.match(orderEvidence({}),/Not realised yet/);
 assert.match(orderEvidence({status:'delivered'}),/Outcome records incomplete/);
 assert.match(orderEvidence({status:'delivered',realised:true}),/Cost records incomplete/);
 assert.match(orderEvidence({status:'delivered',realised:true,payment_status:'unpaid'}),/Payment evidence incomplete/);
 assert.match(orderEvidence({status:'cancelled'}),/No cooked outcome recorded/);
 assert.match(orderEvidence({status:'delivered',realised:true,food_contribution:'0.00',missing:[]}),/RM 0.00 food contribution/);
 assert.match(orderEvidence({status:'delivered',realised:true,food_contribution:'-2.00',missing:[]}),/RM -2.00 food contribution/);
 assert.match(orderEvidence({}),/missing costs are not treated as zero/);
 console.log('Product UX: loading/error counts, enabled payment options and collapsed demo disclosure passed.');
 console.log('Financial UX: unavailable vs genuine zero, negative contribution, unrealised and incomplete outcomes passed.');
}finally{await server.close();}
