import assert from 'node:assert/strict';
import {basketDateIssue,upcomingBasketDates} from './basketOrderingDates.js';
import {basketDaysText} from './deliveryDays.js';
const item=(name,days,extra={})=>({product:{name,delivery_weekdays:days,...extra}});
const salad=item('Salad',[0,1,2,3,4]),monday=item('Monday rice bowl',[0]);
const afterLunch=Date.parse('2026-11-06T12:00:00+08:00');
assert.deepEqual(upcomingBasketDates([salad],'11:00',afterLunch),['2026-11-09','2026-11-10','2026-11-11','2026-11-12','2026-11-13','2026-11-16','2026-11-17']);
assert.deepEqual(upcomingBasketDates([salad,monday],'11:00',afterLunch).slice(0,3),['2026-11-09','2026-11-16','2026-11-23']);
assert.deepEqual(upcomingBasketDates([salad,item('Weekend',[5,6])],'11:00',afterLunch),[]);
assert.deepEqual(upcomingBasketDates([],'11:00',afterLunch),[]);
assert.deepEqual(upcomingBasketDates([salad,item('Fixed sale',[],{delivery_dates:['2026-11-07','2026-11-09']})],'11:00',afterLunch),['2026-11-09']);
const cutoff=item('Bento',[0],{order_cutoff_time:'17:00:00',order_cutoff_days_before:1});
assert.equal(upcomingBasketDates([cutoff],'11:00',Date.parse('2026-11-08T17:00:00+08:00'))[0],'2026-11-16');
assert.equal(upcomingBasketDates([salad],'11:00',Date.parse('2026-11-06T08:00:00+08:00'))[0],'2026-11-06');
assert.equal(upcomingBasketDates([salad],'07:30',Date.parse('2026-11-06T08:00:00+08:00'))[0],'2026-11-09');
assert.match(basketDateIssue([salad,monday],'2026-11-10','11:00',afterLunch),/Choose Monday/);
assert.match(basketDateIssue([salad],'2026-11-06','11:00',afterLunch),/hours have ended/);
assert.match(basketDateIssue([salad],'2026-11-05','11:00',afterLunch),/date has passed/);
assert.match(basketDateIssue([salad],'2027-03-01','11:00',afterLunch),/next 90 days/);
assert.match(basketDateIssue([salad],'2026-02-30','11:00',afterLunch),/valid date/);
assert.deepEqual(upcomingBasketDates([item('Later sale',[],{delivery_dates:['2027-11-06']})],'11:00',afterLunch),[]);
assert.equal(basketDaysText([salad]),'Monday–Friday');assert.equal(basketDaysText([item('Any day',[])]),'Every day');
console.log('Basket ordering dates: shared weekdays/fixed dates, cutoffs, Malaysia day boundaries and handover-hour limits passed. Dates do not certify stock.');
