import assert from 'node:assert/strict';
import {shoppingSuggestions,shoppingPreview,shoppingAdded} from './shoppingResponse.js';
const total={subtotal:'60.00',discount:'0.00',shipping:'0.00',total:'60.00',quantity:6};
const result={id:20,name:'Nasi Ayam Kunyit',price:'10.00',quantity:6,addition_subtotal:'60.00',basket_after:total,delivery_day_allowed:true};
const response={draft:{portions:6,date:'2026-10-20',budget:'80.00'},mode:'guided',missing:[],results:[result],basket_known:true,basket_total:null};
assert.equal(shoppingSuggestions(response),response);
assert.equal(shoppingSuggestions({...response,mode:'owner_review',draft:{},results:[]}).mode,'owner_review');
for(const changed of [{mode:'autopay'},{results:[{...result,price:'0.01<script>'}]},{results:[{...result,quantity:NaN}]},{results:[{...result,basket_after:{...total,total:null}}]},{missing:['charge']},{draft:{portions:0}}])assert.throws(()=>shoppingSuggestions({...response,...changed}));
const addition={product_id:20,menu:'Nasi Ayam Kunyit',quantity:6,quantity_before:0,quantity_after:6,unit_price:'10.00',basket_before:null,basket_after:total};
const preview={preview:addition,confirm:'signed-token'};
assert.equal(shoppingPreview(preview),preview);
assert.throws(()=>shoppingPreview({...preview,confirm:''}));
assert.throws(()=>shoppingPreview({...preview,preview:{...addition,quantity_after:12}}));
const added={added:true,already_applied:false,basket_changed:false,result:addition};
assert.equal(shoppingAdded(added,addition),added);
assert.equal(shoppingAdded({...added,already_applied:true,basket_changed:true},addition).already_applied,true);
assert.throws(()=>shoppingAdded({...added,result:{...addition,product_id:21}},addition));
assert.throws(()=>shoppingAdded({...added,result:{...addition,basket_after:{...total,total:'0.01'}}},addition));
assert.throws(()=>shoppingAdded({...added,added:false},addition));
console.log('Shopping responses: grounded totals, incomplete/owner requests, signed preview shape and exact confirmation identity passed.');
