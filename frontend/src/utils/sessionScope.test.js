import assert from 'node:assert/strict';
import {authSession,scopeStorage} from './sessionScope.js';
import {mutationAttempt} from './checkoutStorage.js';
import {walletData,walletBalance} from './walletResponse.js';
const a=authSession({authenticated:true,user_id:1,username:'alice',is_admin:false});
const b=authSession({authenticated:true,user_id:2,username:'bob',is_admin:false});
assert.notEqual(a.accountKey,b.accountKey);
assert.notEqual(a.accountKey,authSession({authenticated:true,user_id:1,username:'alice',is_admin:true}).accountKey);
assert.equal(authSession({authenticated:false}).isAuthenticated,false);
for(const data of [null,{}, {authenticated:true}, {authenticated:true,username:'alice',is_admin:false,user_id:-1}])assert.throws(()=>authSession(data));
const map=new Map(), storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
scopeStorage(storage,a.accountKey);
storage.setItem('preferredDelivery','2026-10-24');storage.setItem('checkoutAttempt','private-retry');storage.setItem('theme','light');
scopeStorage(storage,a.accountKey);assert.equal(storage.getItem('checkoutAttempt'),'private-retry');
scopeStorage(storage,b.accountKey);assert.equal(storage.getItem('checkoutAttempt'),null);assert.equal(storage.getItem('preferredDelivery'),null);assert.equal(storage.getItem('theme'),'light');
assert.doesNotThrow(()=>scopeStorage({getItem(){throw Error('Blocked')}},a.accountKey));
const id='11111111-1111-4111-8111-111111111111';
const first=mutationAttempt(storage,'walletTopupAttempt',a.accountKey+':5',()=>id);
assert.equal(mutationAttempt(storage,'walletTopupAttempt',a.accountKey+':5',()=>{throw Error('Retry must retain id')}).id,first.id);
scopeStorage(storage,a.accountKey);storage.setItem('walletTopupAttempt','old');scopeStorage(storage,b.accountKey);assert.equal(storage.getItem('walletTopupAttempt'),null);
const wallet={id:1,balance:10.25,wallet_address:'fixture-wallet'};
assert.equal(walletData(wallet),wallet);assert.equal(walletBalance({balance:15}),15);
for(const balance of [NaN,Infinity,-1,'10',null,100000000])assert.throws(()=>walletBalance({balance}));
assert.throws(()=>walletData({...wallet,id:0}));
console.log('Session isolation: distinct account/role scope, retained same-account retries, cross-account checkout clearing, blocked storage and finite wallet responses passed.');
